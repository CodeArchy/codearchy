#!/usr/bin/env node
/**
 * Regenerates @codearchy/conformance's src/expected/polyglot.ts from the
 * current engine. Lives here (not in the conformance package) so the
 * conformance suite never depends on a platform. Run after an intended change
 * to extraction or resolution, and review the diff: it IS the behaviour change.
 *
 *   pnpm --filter @codearchy/platform-node run golden
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildGraph, classifyFiles, DEFAULT_EXCLUDE_PATTERNS, DEFAULT_LANGUAGE_IDS, readManifests } from '@codearchy/core';
import { createNodeAnalyzer, walkFiles } from '../dist/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..', '..', '..', 'fixtures', 'polyglot');
const d = classifyFiles(await walkFiles(root), { languages: DEFAULT_LANGUAGE_IDS, excludePatterns: DEFAULT_EXCLUDE_PATTERNS, maxFiles: 0 }, 'walk');
const { analyzer, fs: fsPort } = await createNodeAnalyzer({ root, maxFileSize: 1_000_000 });
const analyses = await analyzer.analyzeAll(d.sourceFiles);
const g = buildGraph(analyses.values(), await readManifests(fsPort, d.manifests));
if (g.metadata.parserStats.regex !== 0) throw new Error('golden must be produced with tree-sitter for every file');
const golden = {
    files: d.sourceFiles,
    edges: g.edges.map((e) => `${e.source} -> ${e.target}`).sort(),
    symbols: g.metadata.totalSymbols,
};
const out = path.join(here, '..', '..', 'conformance', 'src', 'expected', 'polyglot.ts');
fs.writeFileSync(
    out,
    `/**\n * Golden output for fixtures/polyglot. GENERATED by packages/platform-node/scripts/update-golden.mjs; review diffs.\n * Every platform must reproduce it exactly (Node and every browser engine).\n */\nexport const GOLDEN_POLYGLOT = ${JSON.stringify(golden, null, 4)};\n`
);
console.log(`golden: ${golden.files.length} files, ${golden.edges.length} edges, ${golden.symbols} symbols → ${path.relative(process.cwd(), out)}`);
